/**
 * Generates specs/tokens/tailwind-utility-reference.md — the map from design
 * tokens (globals.css) to the `tw:` utility classes that reference them, plus
 * the value→utility table the codemod uses. Regenerable, so it can't drift.
 *
 * Run: node scripts/design-tokens/gen-tailwind-reference.js
 */
const fs = require('fs');
const path = require('path');

const UI = path.resolve(__dirname, '../..');
const UPSTREAM = require('./upstream-palette.json').palette; // canon-hex -> --color-<name>
const OUT = path.join(UI, 'specs/tokens/tailwind-utility-reference.md');

const SEMANTIC = {
  Background: ['bg-primary', 'bg-secondary', 'bg-tertiary', 'bg-quaternary', 'bg-disabled', 'bg-overlay', 'bg-brand-primary', 'bg-brand-solid', 'bg-error-primary', 'bg-warning-primary', 'bg-success-primary'],
  Text: ['text-primary', 'text-secondary', 'text-tertiary', 'text-quaternary', 'text-disabled', 'text-placeholder', 'text-white', 'text-brand-primary', 'text-error-primary', 'text-warning-primary', 'text-success-primary'],
  Border: ['border-primary', 'border-secondary', 'border-tertiary', 'border-disabled', 'border-error', 'border-brand'],
  Foreground: ['text-fg-brand-primary', 'text-fg-error-primary', 'text-fg-warning-primary', 'text-fg-success-primary'],
};

const SPACING = [
  ['0', '0'], ['0.5', '2px'], ['1', '4px'], ['1.5', '6px'], ['2', '8px'], ['2.5', '10px'],
  ['3', '12px'], ['3.5', '14px'], ['4', '16px'], ['5', '20px'], ['6', '24px'], ['7', '28px'],
  ['8', '32px'], ['9', '36px'], ['10', '40px'], ['11', '44px'], ['12', '48px'], ['14', '56px'],
  ['16', '64px'], ['20', '80px'], ['24', '96px'],
];
const RADIUS = [['none', '0'], ['xs', '2px'], ['sm', '4px'], ['md', '6px'], ['lg', '8px'], ['xl', '12px'], ['2xl', '16px'], ['3xl', '24px'], ['full', '9999px']];
const TEXT = [['xs', '12px'], ['sm', '14px'], ['md', '16px'], ['lg', '18px'], ['xl', '20px'], ['display-xs', '24px'], ['display-sm', '30px'], ['display-md', '36px'], ['display-lg', '48px']];

function main() {
  const palette = Object.entries(UPSTREAM)
    .map(([canon, v]) => ({ hex: canon, suffix: v.replace(/^--color-/, '') }))
    .filter((e) => e.hex.startsWith('#'))
    .sort((a, b) => a.suffix.localeCompare(b.suffix, undefined, { numeric: true }));

  let md =
    '# Tailwind utility reference\n\n' +
    '> Generated by `node scripts/design-tokens/gen-tailwind-reference.js` from ' +
    '`globals.css`. The go-forward styling system: UntitledUI components + ' +
    'Tailwind (`tw:` prefix). Never hardcode a value — use these utilities. ' +
    'The Antd/Less `--om-*` layer ([token-reference.md](./token-reference.md)) is legacy.\n\n' +
    '## Semantic color utilities (prefer these — they adapt to dark mode)\n\n';
  for (const [group, list] of Object.entries(SEMANTIC)) {
    md += `**${group}:** ` + list.map((u) => `\`tw:${u}\``).join(', ') + '\n\n';
  }

  md += '## Spacing (`tw:p-*`, `tw:m-*`, `tw:gap-*`)\n\n| Utility step | px |\n| --- | --- |\n';
  md += SPACING.map(([s, px]) => `| \`${s}\` | ${px} |`).join('\n') + '\n\n';
  md += 'Arbitrary spacing (`tw:p-[13px]`) is a violation — round to the scale.\n\n';

  md += '## Radius (`tw:rounded-*`)\n\n| Utility | value |\n| --- | --- |\n';
  md += RADIUS.map(([s, v]) => `| \`tw:rounded-${s}\` | ${v} |`).join('\n') + '\n\n';

  md += '## Font size (`tw:text-*`)\n\n| Utility | value |\n| --- | --- |\n';
  md += TEXT.map(([s, v]) => `| \`tw:text-${s}\` | ${v} |`).join('\n') + '\n\n';

  md += `## Palette color utilities (${palette.length})\n\n` +
    'Fixed swatches. Prefer a semantic utility above where one fits. Use as ' +
    '`tw:bg-<suffix>`, `tw:text-<suffix>`, `tw:border-<suffix>`, `tw:fill-<suffix>`.\n\n' +
    '<details><summary>Show all</summary>\n\n| Suffix | Hex | Example |\n| --- | --- | --- |\n';
  md += palette.map((e) => `| \`${e.suffix}\` | \`${e.hex}\` | \`tw:bg-${e.suffix}\` |`).join('\n');
  md += '\n\n</details>\n';

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, md);
  process.stdout.write(`Wrote ${OUT} (${palette.length} palette + semantic/spacing/radius/text)\n`);
}

main();
