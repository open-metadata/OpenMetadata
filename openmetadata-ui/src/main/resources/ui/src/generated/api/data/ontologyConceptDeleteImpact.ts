/**
 * What deleting one ontology concept touches. Relationships and rules are removed together
 * with the concept; blockers must be edited by hand before the concept can be deleted.
 * Catalog bindings are listed by the bindings endpoint.
 */
export interface OntologyConceptDeleteImpact {
    /**
     * Properties and concepts that point at this concept through a domain, range or replacement.
     */
    blockers: EntityReference[];
    /**
     * Concepts whose named parent is this concept. They keep existing and move to the top level.
     */
    children: EntityReference[];
    concept:  EntityReference;
    /**
     * Hierarchy and link axioms that name this concept as subject or as a parent or filler.
     */
    relationships: EntityReference[];
    /**
     * All other axioms that name this concept.
     */
    rules: EntityReference[];
}

/**
 * This schema defines the EntityReference type used for referencing an entity.
 * EntityReference is used for capturing relationships from one entity to another. For
 * example, a table has an attribute called database of type EntityReference that captures
 * the relationship of a table `belongs to a` database.
 */
export interface EntityReference {
    /**
     * If true the entity referred to has been soft-deleted.
     */
    deleted?: boolean;
    /**
     * Optional description of entity.
     */
    description?: string;
    /**
     * Display Name that identifies this entity.
     */
    displayName?: string;
    /**
     * Fully qualified name of the entity instance. For entities such as tables, databases
     * fullyQualifiedName is returned in this field. For entities that don't have name hierarchy
     * such as `user` and `team` this will be same as the `name` field.
     */
    fullyQualifiedName?: string;
    /**
     * Link to the entity resource.
     */
    href?: string;
    /**
     * Unique identifier that identifies an entity instance.
     */
    id: string;
    /**
     * If true the relationship indicated by this entity reference is inherited from the parent
     * entity.
     */
    inherited?: boolean;
    /**
     * Name of the entity instance.
     */
    name?: string;
    /**
     * Entity type/class name - Examples: `database`, `table`, `metrics`, `databaseService`,
     * `dashboardService`...
     */
    type: string;
}
