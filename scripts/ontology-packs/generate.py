#!/usr/bin/env python3
"""Generate the bundled ontology library packs from scripts/ontology-packs/sources.json.

Upstream payloads are written byte for byte as published, so every IRI stays the publisher's. Turtle
stays Turtle and RDF/XML stays RDF/XML, and the importer reads both.

The one exception is a module that declares "convert": "turtle". The importer's XXE guard refuses
every XML DOCTYPE, so a source that opens with an entity-declaring DOCTYPE cannot be read as
published. The generator verifies the download against its pinned sourceSha256, converts it to
Turtle, proves the result triple-isomorphic to the source (rdflib graph isomorphism) and writes it as
sorted N-Triples-style Turtle with canonical, module-unique blank-node labels, so a rerun is byte-identical. The
checked-in payload is pinned by payloadSha256 and the converted triples are unchanged; only the
serialization differs.

The standard library is enough for everything except a conversion. A conversion needs rdflib
(`pip install rdflib`), a dev-only dependency imported only when a module is actually converted.
`--check` and a run that finds every payload already current never import it.

  generate.py              write payloads, manifests, index, README and the NOTICE block
  generate.py --check      verify the checked-in files match sources.json, offline
  generate.py --pin        download modules whose sourceSha256 (or converted payloadSha256) is null
                           and record the hash
  generate.py --cache DIR  keep and reuse downloads in DIR

A payload that is already checked in and matches its pinned hash (sourceSha256, or payloadSha256 for a
converted module) is never downloaded again, so a second run changes nothing.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parents[2]
SOURCES = Path(__file__).with_name("sources.json")
PAYLOAD_DIR = ROOT / "openmetadata-spec/src/main/resources/rdf/ontology-packs"
MANIFEST_DIR = ROOT / "openmetadata-service/src/main/resources/json/data/ontology/packs"
NOTICE = ROOT / "NOTICE"
NOTICE_BEGIN = "# BEGIN ontology-packs (generated by scripts/ontology-packs/generate.py)"
NOTICE_END = "# END ontology-packs"
EXTENSIONS = {"turtle": "ttl", "rdfxml": "rdf"}
ID_PATTERN = re.compile(r"^[a-z][a-z0-9-]*$")
USER_AGENT = "OpenMetadata-ontology-pack-generator/1"

OWL = "http://www.w3.org/2002/07/owl#"
RDFS = "http://www.w3.org/2000/01/rdf-schema#"
RDF = "http://www.w3.org/1999/02/22-rdf-syntax-ns#"
SKOS = "http://www.w3.org/2004/02/skos/core#"
CONCEPT_TYPES = {OWL + "Class", RDFS + "Class", SKOS + "Concept"}
EDGE_PREDICATES = {
    RDFS + "subClassOf",
    RDFS + "subPropertyOf",
    SKOS + "broader",
    SKOS + "narrower",
    SKOS + "related",
}


class GeneratorError(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def payload_format(module: dict) -> str:
    return module.get("convert") or module["format"]


def payload_name(pack: dict, module: dict) -> str:
    return f"{pack['id']}/{module['id']}.{EXTENSIONS[payload_format(module)]}"


def resource_path(pack: dict, module: dict) -> str:
    return f"rdf/ontology-packs/{payload_name(pack, module)}"


# ----------------------------------------------------------------------------- counting


_TOKEN = re.compile(
    r"""
    (?P<ws>\s+|\#[^\n]*)
  | (?P<iri><[^<>"{}|^`\\\x00-\x20]*>)
  | (?P<long>\"\"\"(?:[^"\\]|\\.|"(?!""))*\"\"\"|'''(?:[^'\\]|\\.|'(?!''))*''')
  | (?P<str>"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')
  | (?P<directive>@prefix|@base)
  | (?P<lang>@[A-Za-z]+(?:-[A-Za-z0-9]+)*)
  | (?P<dt>\^\^)
  | (?P<bnode>_:[A-Za-z0-9_](?:[A-Za-z0-9_.-]*[A-Za-z0-9_-])?)
  | (?P<pname>(?:[^\W\d][\w.-]*)?:(?:(?:[\w:%]|\\.)(?:(?:[\w:%-]|\\.|\.(?=[\w:%\\-]))*)?)?)
  | (?P<number>[+-]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?)
  | (?P<word>[A-Za-z]+)
  | (?P<punct>[;,.\[\]()])
    """,
    re.VERBOSE,
)


class TurtleScan:
    """Reads the triples of a Turtle document; only what counting needs is retained."""

    def __init__(self, text: str):
        self.tokens = list(self._tokenize(text))
        self.pos = 0
        self.prefixes: dict[str, str] = {}
        self.base = ""
        self.bnodes = 0
        self.triples: list[tuple[str, str, str]] = []

    @staticmethod
    def _tokenize(text: str):
        pos = 0
        end = len(text)
        while pos < end:
            match = _TOKEN.match(text, pos)
            if not match:
                raise GeneratorError(f"Turtle token error near offset {pos}: {text[pos:pos + 40]!r}")
            pos = match.end()
            kind = match.lastgroup
            if kind != "ws":
                yield kind, match.group()

    def _peek(self):
        return self.tokens[self.pos] if self.pos < len(self.tokens) else (None, None)

    def _next(self):
        token = self._peek()
        self.pos += 1
        return token

    def _expect(self, value: str):
        kind, text = self._next()
        if text != value:
            raise GeneratorError(f"Turtle: expected {value!r}, found {text!r}")

    def _iri(self, raw: str) -> str:
        value = raw[1:-1]
        if ":" not in value.split("/", 1)[0] and self.base:
            return urljoin(self.base, value)
        return value

    def _pname(self, raw: str) -> str:
        prefix, _, local = raw.partition(":")
        if prefix not in self.prefixes:
            raise GeneratorError(f"Turtle: undeclared prefix {prefix!r}")
        value = self.prefixes[prefix] + local.replace("\\", "")
        if ":" not in value.split("/", 1)[0] and self.base:
            return urljoin(self.base, value)
        return value

    def _blank(self) -> str:
        self.bnodes += 1
        return f"_:g{self.bnodes}"

    def scan(self) -> list[tuple[str, str, str]]:
        while self._peek()[0] is not None:
            kind, text = self._peek()
            if kind == "directive" or (kind == "word" and text.upper() in ("PREFIX", "BASE")):
                self._directive()
            else:
                subject = self._subject()
                if self._peek()[1] != ".":
                    self._predicate_object_list(subject)
                self._expect(".")
        return self.triples

    def _directive(self):
        _, text = self._next()
        sparql = not text.startswith("@")
        if text.lower().lstrip("@") == "prefix":
            _, name = self._next()
            _, iri = self._next()
            self.prefixes[name[:-1]] = self._iri(iri)
        else:
            _, iri = self._next()
            self.base = self._iri(iri)
        if not sparql:
            self._expect(".")

    def _subject(self) -> str:
        kind, text = self._peek()
        if text == "[":
            return self._blank_property_list()
        if text == "(":
            return self._collection()
        self._next()
        return self._term(kind, text)

    def _term(self, kind: str, text: str) -> str:
        if kind == "iri":
            return self._iri(text)
        if kind == "pname":
            return self._pname(text)
        if kind == "bnode":
            return text
        raise GeneratorError(f"Turtle: unexpected term {text!r} near {self.tokens[max(0, self.pos - 6):self.pos + 3]}")

    def _predicate_object_list(self, subject: str):
        while True:
            kind, text = self._next()
            predicate = RDF + "type" if (kind == "word" and text == "a") else self._term(kind, text)
            while True:
                obj = self._object()
                self.triples.append((subject, predicate, obj))
                if self._peek()[1] == ",":
                    self._next()
                    continue
                break
            if self._peek()[1] != ";":
                return
            while self._peek()[1] == ";":
                self._next()
            if self._peek()[1] in (".", "]"):
                return

    def _object(self) -> str:
        kind, text = self._peek()
        if text == "[":
            return self._blank_property_list()
        if text == "(":
            return self._collection()
        self._next()
        if kind in ("str", "long"):
            if self._peek()[0] == "lang":
                self._next()
            elif self._peek()[0] == "dt":
                self._next()
                self._next()
            return '"'
        if kind in ("number", "word"):
            return '"'
        return self._term(kind, text)

    def _blank_property_list(self) -> str:
        self._expect("[")
        node = self._blank()
        if self._peek()[1] != "]":
            self._predicate_object_list(node)
        self._expect("]")
        return node

    def _collection(self) -> str:
        self._expect("(")
        node = self._blank()
        while self._peek()[1] != ")":
            self._object()
        self._expect(")")
        return node


def _is_iri(term: str) -> bool:
    return not term.startswith("_:") and term != '"'


def count_turtle(text: str) -> tuple[int, int]:
    triples = TurtleScan(text).scan()
    concepts = {s for s, p, o in triples if p == RDF + "type" and o in CONCEPT_TYPES and _is_iri(s)}
    edges = {
        (s, p, o) for s, p, o in triples if p in EDGE_PREDICATES and _is_iri(s) and _is_iri(o)
    }
    return len(concepts), len(edges)


def count_rdfxml(data: bytes) -> tuple[int, int]:
    about = f"{{{RDF}}}about"
    resource = f"{{{RDF}}}resource"
    class_tags = {f"{{{OWL}}}Class", f"{{{RDFS}}}Class", f"{{{SKOS}}}Concept"}
    edge_tags = {RDFS + "subClassOf", RDFS + "subPropertyOf", SKOS + "broader",
                 SKOS + "narrower", SKOS + "related"}
    concepts: set[str] = set()
    edges: set[tuple[str, str, str]] = set()
    for node in ET.fromstring(data):
        subject = node.get(about)
        if subject is None:
            continue
        typed = node.tag in class_tags
        for child in node:
            target = child.get(resource)
            tag = child.tag.replace("{", "", 1).replace("}", "")
            if tag == RDF + "type" and target in {t.replace("{", "").replace("}", "") for t in class_tags}:
                typed = True
            if tag in edge_tags and target is not None:
                edges.add((subject, tag, target))
        if typed:
            concepts.add(subject)
    return len(concepts), len(edges)


def count(module: dict, data: bytes) -> tuple[int, int]:
    if payload_format(module) == "turtle":
        return count_turtle(data.decode("utf-8"))
    return count_rdfxml(data)


# ----------------------------------------------------------------------------- loading


def load_sources() -> dict:
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    validate(sources)
    return sources


def validate(sources: dict) -> None:
    allowed = set(sources["allowedLicenses"])
    excluded = {entry["id"] for entry in sources["excluded"]}
    seen: set[str] = set()
    for pack in sources["packs"]:
        pid = pack["id"]
        if not ID_PATTERN.match(pid) or pid in seen:
            raise GeneratorError(f"Pack id {pid!r} is invalid or duplicated")
        seen.add(pid)
        if pid in excluded:
            raise GeneratorError(f"Pack {pid} is also listed as excluded")
        if pack["license"] not in allowed:
            raise GeneratorError(f"Pack {pid} has license {pack['license']!r}, which is not allowed")
        if pack["origin"] not in ("upstream", "authored"):
            raise GeneratorError(f"Pack {pid} has an unknown origin")
        module_ids = [m["id"] for m in pack["modules"]]
        if len(set(module_ids)) != len(module_ids) or not all(ID_PATTERN.match(m) for m in module_ids):
            raise GeneratorError(f"Pack {pid} has invalid or duplicated module ids")
        for module in pack["modules"]:
            if module["format"] not in EXTENSIONS:
                raise GeneratorError(f"{pid}/{module['id']} has an unsupported format")
            if module.get("convert") not in (None, "turtle"):
                raise GeneratorError(f"{pid}/{module['id']} can only convert to turtle")
            if module.get("convert") and (pack["origin"] != "upstream" or module["format"] == "turtle"):
                raise GeneratorError(f"{pid}/{module['id']} converts an upstream non-Turtle source only")
            if pack["origin"] == "upstream" and not module.get("url"):
                raise GeneratorError(f"{pid}/{module['id']} needs a pinned url")
            if not set(module.get("dependencies", [])) <= set(module_ids):
                raise GeneratorError(f"{pid}/{module['id']} depends on an unknown module")


# ----------------------------------------------------------------------------- outputs


def build_manifest(pack: dict, payloads: dict[str, bytes]) -> dict:
    modules = []
    for module in pack["modules"]:
        data = payloads[payload_name(pack, module)]
        try:
            concepts, relationships = count(module, data)
        except GeneratorError as error:
            raise GeneratorError(f"{pack['id']}/{module['id']}: {error}") from error
        entry = {
            "id": module["id"],
            "name": module["name"],
            "description": module["description"],
            "format": payload_format(module),
            "resourcePath": resource_path(pack, module),
            "sha256": sha256(data),
            "conceptCount": concepts,
            "relationshipCount": relationships,
            "dependencies": module.get("dependencies", []),
            "selectedByDefault": module.get("selectedByDefault", True),
        }
        if pack["origin"] == "upstream":
            entry["sourceUrl"] = module["url"]
        if module.get("convert"):
            entry["sourceSha256"] = module["sourceSha256"]
        modules.append(entry)
    manifest = {
        "id": pack["id"],
        "name": pack["name"],
        "abbreviation": pack["abbreviation"],
        "standard": pack["standard"],
        "publisher": pack["publisher"],
        "industry": pack["industry"],
        "layer": pack["layer"],
        "version": pack["version"],
        "description": pack["description"],
        "license": pack["license"],
        "licenseUrl": pack["licenseUrl"],
        "sourceUrl": pack["sourceUrl"],
        "attribution": pack["attribution"],
        "bundled": True,
        "modules": modules,
    }
    return manifest


def dump_json(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def build_readme(sources: dict) -> str:
    lines = [
        "# Ontology library payloads",
        "",
        "Generated by `scripts/ontology-packs/generate.py` from `scripts/ontology-packs/sources.json`.",
        "Do not edit by hand; run `make ontology-packs` instead.",
        "",
        "Upstream packs are the publisher's files, byte for byte, at the pinned URL below. IRIs are",
        "the publisher's. The `sha256` column is the hash of the file as published and as stored here.",
        "A `converted` row is a source the importer's XXE guard cannot read as published (an RDF/XML",
        "DOCTYPE declaring entities): the generator converted it to Turtle and proved the triples",
        "isomorphic to the source; the row shows the source hash and the stored payload hash.",
        "Authored packs are OpenMetadata-written outlines (Apache License 2.0) with OpenMetadata IRIs.",
        "",
        "| Pack | Version | License | Module file | Source | sha256 |",
        "|---|---|---|---|---|---|",
    ]
    for pack in sources["packs"]:
        for module in pack["modules"]:
            source = module.get("url", "OpenMetadata-authored")
            digest = f"`{module.get('sourceSha256') or 'authored'}`"
            if module.get("convert"):
                digest = f"converted: source {digest}, payload `{module.get('payloadSha256')}`"
            lines.append(
                f"| {pack['id']} | {pack['version']} | {pack['license']} | "
                f"`{payload_name(pack, module)}` | {source} | {digest} |"
            )
    lines += ["", "## Not bundled", ""]
    lines += [f"- **{e['name']}**: {e['reason']}" for e in sources["excluded"]]
    lines += ["", "## Attribution", ""]
    lines += [f"- **{p['name']}**: {p['attribution']}" for p in sources["packs"]]
    return "\n".join(lines) + "\n"


def build_notice_block(sources: dict) -> str:
    lines = [
        NOTICE_BEGIN,
        "------------------------------------------------------------------------------",
        "This distribution bundles the following third-party ontologies, redistributed",
        "without changes in openmetadata-spec/src/main/resources/rdf/ontology-packs/, except that a",
        "source the importer cannot read as published is converted to Turtle, triples unchanged.",
        "",
    ]
    for pack in sources["packs"]:
        if pack["origin"] != "upstream":
            continue
        lines += [
            f"  {pack['name']} {pack['version']}",
            f"  {pack['attribution']}",
            f"  {pack['sourceUrl']}",
            f"  License: {pack['license']}, {pack['licenseUrl']}",
            "",
        ]
    lines.append(NOTICE_END)
    return "\n".join(lines) + "\n"


def apply_notice(current: str, block: str) -> str:
    start = current.find(NOTICE_BEGIN)
    if start == -1:
        return current.rstrip("\n") + "\n\n" + block
    end = current.index(NOTICE_END, start) + len(NOTICE_END)
    return current[:start] + block.rstrip("\n") + current[end:]


# ----------------------------------------------------------------------------- download


def download(module: dict, cache: Path | None) -> bytes:
    name = re.sub(r"[^A-Za-z0-9._-]", "_", module["url"])
    if cache is not None and (cache / name).exists():
        return (cache / name).read_bytes()
    request = urllib.request.Request(
        module["url"],
        headers={"User-Agent": USER_AGENT, "Accept": module.get("accept", "*/*")},
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        data = response.read()
    if cache is not None:
        cache.mkdir(parents=True, exist_ok=True)
        (cache / name).write_bytes(data)
    return data


def convert_to_turtle(name: str, source: bytes) -> bytes:
    try:
        from rdflib import BNode, Graph
        from rdflib.compare import isomorphic, to_canonical_graph
    except ImportError as error:
        raise GeneratorError(f"{name} needs conversion, which needs rdflib: pip install rdflib") from error
    graph = Graph()
    graph.parse(data=source, format="xml")
    # Canonical labels repeat across files, and the preview joins module bodies, so make them
    # module-unique or two modules' blank nodes would merge.
    scope = re.sub(r"[^A-Za-z0-9]", "", name.rsplit(".", 1)[0])
    unique = Graph()
    for s, p, o in to_canonical_graph(graph):
        unique.add(tuple(BNode(f"{scope}{x}") if isinstance(x, BNode) else x for x in (s, p, o)))
    lines = sorted(unique.serialize(format="nt").splitlines())
    data = ("\n".join(line for line in lines if line) + "\n").encode("utf-8")
    converted = Graph()
    converted.parse(data=data, format="turtle")
    if len(graph) != len(converted) or not isomorphic(graph, converted):
        raise GeneratorError(f"{name}: the Turtle conversion is not isomorphic to the source")
    return data


def obtain_converted(
    name: str, path: Path, module: dict, cache: Path | None, pin: bool, pinned: dict[str, str]
) -> bytes:
    expected = module.get("payloadSha256")
    if expected and path.exists() and sha256(path.read_bytes()) == expected:
        return path.read_bytes()
    if not module.get("sourceSha256"):
        raise GeneratorError(f"{name} has no sourceSha256; pin the source first")
    if not expected and not pin:
        raise GeneratorError(f"{name} has no payloadSha256; run with --pin to record it")
    source = download(module, cache)
    digest = sha256(source)
    if digest != module["sourceSha256"]:
        raise GeneratorError(
            f"{name}: {module['url']} hashes to {digest}, pinned {module['sourceSha256']}. "
            "The publisher changed the file; review it before re-pinning."
        )
    data = convert_to_turtle(name, source)
    actual = sha256(data)
    if expected and actual != expected:
        raise GeneratorError(f"{name}: conversion hashes to {actual}, pinned {expected}")
    if not expected:
        pinned[module["url"] + "#payload"] = actual
        module["payloadSha256"] = actual
    return data


def obtain_payloads(sources: dict, cache: Path | None, pin: bool) -> dict[str, bytes]:
    payloads: dict[str, bytes] = {}
    pinned: dict[str, str] = {}
    for pack in sources["packs"]:
        for module in pack["modules"]:
            name = payload_name(pack, module)
            path = PAYLOAD_DIR / name
            if pack["origin"] == "authored":
                if not path.exists():
                    raise GeneratorError(f"Authored payload is missing: {path}")
                payloads[name] = path.read_bytes()
                continue
            if module.get("convert"):
                payloads[name] = obtain_converted(name, path, module, cache, pin, pinned)
                continue
            expected = module.get("sourceSha256")
            if expected and path.exists() and sha256(path.read_bytes()) == expected:
                payloads[name] = path.read_bytes()
                continue
            if not expected and not pin:
                raise GeneratorError(f"{name} has no sourceSha256; run with --pin to record it")
            data = download(module, cache)
            digest = sha256(data)
            if expected and digest != expected:
                raise GeneratorError(
                    f"{name}: {module['url']} hashes to {digest}, pinned {expected}. "
                    "The publisher changed the file; review it before re-pinning."
                )
            if not expected:
                pinned[module["url"]] = digest
                module["sourceSha256"] = digest
            payloads[name] = data
    if pinned:
        text = SOURCES.read_text(encoding="utf-8")
        for url, digest in pinned.items():
            field = "payloadSha256" if url.endswith("#payload") else "sourceSha256"
            url = url.removesuffix("#payload")
            pattern = re.compile(
                r'("url": "' + re.escape(url) + r'"(?:(?!"url")[\s\S])*?"' + field + r'": )null'
            )
            text, hits = pattern.subn(lambda m: m.group(1) + f'"{digest}"', text, count=1)
            if hits != 1:
                raise GeneratorError(f"Could not record the pin for {url}")
            print(f"pinned {url} {digest}")
        SOURCES.write_text(text, encoding="utf-8")
    return payloads


# ----------------------------------------------------------------------------- run


def expected_outputs(sources: dict, payloads: dict[str, bytes]) -> dict[Path, bytes]:
    outputs: dict[Path, bytes] = {}
    for pack in sources["packs"]:
        for module in pack["modules"]:
            name = payload_name(pack, module)
            outputs[PAYLOAD_DIR / name] = payloads[name]
        outputs[MANIFEST_DIR / f"{pack['id']}.json"] = dump_json(
            build_manifest(pack, payloads)
        ).encode("utf-8")
    index = {"packs": sorted(pack["id"] for pack in sources["packs"])}
    outputs[MANIFEST_DIR / "index.json"] = dump_json(index).encode("utf-8")
    outputs[PAYLOAD_DIR / "README.md"] = build_readme(sources).encode("utf-8")
    notice = apply_notice(NOTICE.read_text(encoding="utf-8"), build_notice_block(sources))
    outputs[NOTICE] = notice.encode("utf-8")
    return outputs


def stray_files(outputs: dict[Path, bytes]) -> list[Path]:
    stray = []
    for directory in (PAYLOAD_DIR, MANIFEST_DIR):
        for path in sorted(directory.rglob("*")):
            if path.is_file() and path not in outputs:
                stray.append(path)
    return stray


def check(sources: dict) -> int:
    problems = []
    payloads: dict[str, bytes] = {}
    for pack in sources["packs"]:
        for module in pack["modules"]:
            name = payload_name(pack, module)
            path = PAYLOAD_DIR / name
            if not path.exists():
                problems.append(f"missing payload {path.relative_to(ROOT)}")
                continue
            payloads[name] = path.read_bytes()
            pin = module.get("payloadSha256") if module.get("convert") else module.get("sourceSha256")
            if pack["origin"] == "upstream" and sha256(payloads[name]) != pin:
                problems.append(f"{name} is not the pinned payload (sha256 differs)")
    if problems:
        print("\n".join(problems))
        return 1
    outputs = expected_outputs(sources, payloads)
    for path, data in outputs.items():
        if not path.exists() or path.read_bytes() != data:
            problems.append(f"{path.relative_to(ROOT)} is out of date; run make ontology-packs")
    problems += [f"stray file {p.relative_to(ROOT)}" for p in stray_files(outputs)]
    if problems:
        print("\n".join(problems))
        return 1
    print(f"ontology packs: {len(sources['packs'])} packs match sources.json")
    return 0


def generate(sources: dict, cache: Path | None, pin: bool) -> int:
    payloads = obtain_payloads(sources, cache, pin)
    outputs = expected_outputs(sources, payloads)
    changed = 0
    for path, data in outputs.items():
        if path.exists() and path.read_bytes() == data:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        changed += 1
        print(f"wrote {path.relative_to(ROOT)}")
    for path in stray_files(outputs):
        path.unlink()
        changed += 1
        print(f"removed {path.relative_to(ROOT)}")
    for directory in sorted(PAYLOAD_DIR.iterdir()):
        if directory.is_dir() and not any(directory.iterdir()):
            shutil.rmtree(directory)
    print(f"ontology packs: {changed} file(s) changed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify checked-in files, offline")
    parser.add_argument("--pin", action="store_true", help="record hashes that are still null")
    parser.add_argument("--cache", type=Path, help="directory that keeps downloads")
    args = parser.parse_args()
    try:
        sources = load_sources()
        if args.check:
            return check(sources)
        return generate(sources, args.cache, args.pin)
    except GeneratorError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
